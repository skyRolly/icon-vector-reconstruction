#!/usr/bin/env python3
"""Independent product composition; reuse the historical geometry/light builder.

Never writes historical parameters or reconstruction.svg. The sole geometric
transform of the measured optical motif is a similarity (uniform scale and
translation), so radial effects, normals and diffraction angles stay intact.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path

from build_svg import Builder, f, ribbon_path, squircle_rect_path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "design/anamorph.json"
HISTORICAL = ROOT / "src/params.json"


def load_design(path=CONFIG):
    config = json.loads(Path(path).read_text())
    if config["schema_version"] != 1 or config["canvas"] != 1024:
        raise ValueError("Unsupported product design schema/canvas")
    raw = HISTORICAL.read_bytes()
    if hashlib.sha256(raw).hexdigest() != config["historical_params_sha256"]:
        raise ValueError("Historical parameters changed; review the design dependency explicitly")
    return config, json.loads(raw)


def motif_transform(config):
    m = config["motif"]
    s = m["scale"]
    dx, dy = (c - a * s for c, a in zip(m["center"], m["anchor"]))
    return f'translate({f(dx)} {f(dy)}) scale({f(s)})'


def body_path(config, full_bleed=False):
    b = config["body"]
    inset = 0 if full_bleed else b["inset"]
    radius = b["radius"] * (1024 / (1024 - 2 * b["inset"])) if full_bleed else b["radius"]
    return squircle_rect_path(inset, inset, 1024 - inset, 1024 - inset,
                              radius, b["exponent"])


def optical_params(config, historical, candidate, small=False):
    """A derived in-memory state, never a second mutable reconstruction state."""
    style = config["candidates"][candidate]
    p = copy.deepcopy(historical)
    # The product compositor owns the enclosure. Do not let the old tall frame
    # clip the uniformly positioned optical motif (lens clips remain meaningful).
    p["frame"].update(left=-256, top=-256, right=1280, bottom=1280)
    retained = []
    for layer in p["layers"]:
        kind, name = layer["kind"], layer["id"]
        if kind not in ("arc", "radial", "streak", "vstreak", "ray"):
            continue
        core = kind == "arc" and name.startswith("arc_core")
        if kind == "arc":
            gain = style["core_gain"] if core else style["glow_gain"]
            if small:
                if core:
                    layer["width"] *= config["small"]["core_width_gain"]
                else:
                    gain *= config["small"]["glow_gain"]
            # Historical colour fields describe minute reference differences;
            # keep them for A/baseline, use clean light hierarchy for B/C.
            if candidate in ("B", "C"):
                layer.pop("red_shift", None)
        else:
            gain = style["flare_gain"]
            if kind in ("ray", "vstreak") or name in ("flare_sat_long", "flare_wash_far", "flare_fan"):
                if small:
                    continue
                gain *= style["ray_gain"]
            if small:
                gain *= config["small"]["flare_gain"]
        channel = style["channel_scale"] if kind == "arc" else [1, 1, 1]
        layer["color"] = [min(255, c * gain * q) for c, q in zip(layer["color"], channel)]
        retained.append(layer)
    p["layers"] = retained
    return p


def svg_document(defs, body, label):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
            'viewBox="0 0 1024 1024" color-interpolation="sRGB">\n'
            f'<title>Anamorph — {label}</title>\n'
            '<!-- Generated by src/product_icon.py; editable source: design/anamorph.json. -->\n'
            f'<defs>\n{defs}\n</defs>\n{body}\n</svg>\n')


def crisp_curve(historical, side, width=9.2, inset=0):
    # Closed, tapered filled silhouettes for system material edges. These are
    # derived from the same measured cubics as the precomposed light artwork.
    table = [[85, 0.05], [140, 0.6], [240, 0.95], [500, 1.12],
             [720, 1.0], [870, 0.68], [950, 0.04]]
    return ribbon_path(historical["geometry"]["arc_" + side], side, inset, width, table)


def build_product(config, historical, candidate=None, variant="rounded", small=False):
    candidate = candidate or config["selected"]
    if variant not in ("rounded", "opaque", "apple-square"):
        raise ValueError(variant)
    style = config["candidates"][candidate]
    p = optical_params(config, historical, candidate, small)
    builder = Builder(p)
    motif = []
    if style["glass_band"]:
        for side in ("left", "right"):
            motif.append(f'<path d="{crisp_curve(historical, side, 24, 6)}" '
                         'fill="#39779a" opacity="0.28"/>')
    for layer in p["layers"]:
        motif.append(f'<!-- {layer["id"]} -->\n{builder.layer(layer)}')
    is_apple = variant == "apple-square"
    shape = 'M0,0 H1024 V1024 H0 Z' if is_apple else body_path(config)
    defs = [*builder._filters.values(), *builder.defs,
            f'<clipPath id="product-body"><path d="{shape}"/></clipPath>',
            '<linearGradient id="product-field" x1="0" y1="0" x2="0.75" y2="1">'
            f'<stop stop-color="{style["background"][0]}"/>'
            f'<stop offset="1" stop-color="{style["background"][1]}"/></linearGradient>',
            '<linearGradient id="product-edge" x1="0" y1="0" x2="0.3" y2="1">'
            '<stop stop-color="#738695" stop-opacity="0.55"/>'
            '<stop offset="0.46" stop-color="#386072" stop-opacity="0.2"/>'
            '<stop offset="1" stop-color="#4b6a80" stop-opacity="0.32"/></linearGradient>']
    body = '<rect width="1024" height="1024" fill="#050912"/>\n' if variant == "opaque" else ''
    body += (f'<g clip-path="url(#product-body)">\n'
             f'<path d="{shape}" fill="url(#product-field)"/>\n'
             f'<g transform="{motif_transform(config)}">\n' + '\n'.join(motif) + '\n</g>\n')
    if not is_apple:
        # An enclosure edge, never a simulated metallic rim or extrusion.
        body += f'<path d="{shape}" fill="none" stroke="url(#product-edge)" stroke-width="{style["edge"]}"/>\n'
    body += '</g>'
    return svg_document('\n'.join(defs), body, f'{style["name"]} / {variant}' + (' / small' if small else ''))


def build_apple_layer(config, historical, layer):
    """Import-ready SVGs, not a claim of a validated native .icon project.

    Square canvases, no enclosure mask, blur, screen blend, opacity, shadow or
    system specular treatment. The owner tunes native materials in Composer.
    """
    transform = motif_transform(config)
    if layer in ("left", "right"):
        body = f'<g transform="{transform}"><path d="{crisp_curve(historical, layer)}" fill="#bcefff"/></g>'
    elif layer == "interaction":
        x, y = historical["flare"]["cx"], historical["flare"]["cy"]
        body = (f'<g transform="{transform}"><ellipse cx="{f(x)}" cy="{f(y)}" '
                'rx="5" ry="3.6" fill="#effaff"/>'
                f'<path d="M{f(x-28)},{f(y-0.8)} H{f(x+12)} V{f(y+0.8)} H{f(x-28)} Z" fill="#bcefff"/></g>')
    else:
        raise ValueError(layer)
    return svg_document('', body, f'Icon Composer source / {layer}')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--config', type=Path, default=CONFIG)
    ap.add_argument('--candidate', choices=['square-baseline', 'A', 'B', 'C'])
    ap.add_argument('--variant', choices=['rounded', 'opaque', 'apple-square'], default='rounded')
    ap.add_argument('--small', action='store_true')
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    config, historical = load_design(args.config)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_product(config, historical, args.candidate, args.variant, args.small))


if __name__ == '__main__':
    main()
